import fs from "node:fs";
import path from "node:path";
import { db } from "../../../db.js";
import { getConfiguredThumbnailPath } from "./thumbnail.js";

// Housekeeping for the thumbnail store: remove the empty directories deletions
// leave behind, and COUNT the files nothing points at any more.
//
// Files go unreferenced for ordinary reasons — a restore rolls the database back
// past a scan that already wrote covers, an interrupted delete leaves a face crop
// behind. They are harmless in themselves: every read resolves a storage key out
// of the database, so a file nothing points at is never opened. They are worth
// knowing about, which is what the count is for.
//
// This pass does NOT delete them, and that is deliberate. In a real store of
// 44,910 files, 338 had no matching key — and 322 of those were meant to be
// there. A book's "-cover-large.webp" and a video's "-web.mp4" are generated by
// convention and recorded in no column at all, on purpose. A sweep written the
// obvious way ("no row points at it, remove it") would have deleted every large
// book cover and every transcoded video on the box, on a schedule, unattended.
//
// So the rule below is deliberately reluctant: a file counts as orphaned only
// when its key is unreferenced AND the resource its name is built from no longer
// exists. That is what separated the 16 genuine orphans from the 322 keepers.
// Under-counting is the safe direction for a number nobody acts on automatically;
// over-counting is how a future version talks itself into deleting live data.

// Every column that stores a thumbnail-store key. A key here is an exact relative
// path ("<bucket>/<aa>/<bb>/<file>"), so these are compared verbatim — the store
// lives on a case-sensitive filesystem in every deployment we ship.
const REFERENCED_KEY_QUERIES = [
  "SELECT cover_storage_key AS k FROM item_metadata",
  "SELECT preview_storage_key AS k FROM gallery_details",
  "SELECT thumb_storage_key AS k FROM gallery_faces",
  "SELECT image_storage_key AS k FROM people",
  "SELECT cover_storage_key AS k FROM series",
  "SELECT image_storage_key AS k FROM categories",
  "SELECT portrait_storage_key AS k FROM family_tree_persons",
  "SELECT storage_key AS k FROM gallery_music_tracks",
  "SELECT output_storage_key AS k FROM gallery_slideshows",
  "SELECT storage_key AS k FROM story_audio",
  "SELECT cover_key AS k FROM trashed_items"
];

// Every table whose id a generated filename is built from (thumbnailStorageKey's
// resourceId). A file whose owner is still alive is never orphaned, whatever its
// suffix — this is the clause that spares the derived "-cover-large"/"-web.mp4"
// siblings no column records.
const OWNER_ID_QUERIES = [
  "SELECT id FROM library_items",
  "SELECT id FROM gallery_faces",
  "SELECT id FROM series",
  "SELECT id FROM people",
  "SELECT id FROM categories",
  "SELECT id FROM family_tree_persons",
  "SELECT id FROM gallery_music_tracks",
  "SELECT id FROM gallery_slideshows",
  "SELECT id FROM story_audio"
];

function collect(queries: string[]): Set<string> {
  const found = new Set<string>();
  for (const sql of queries) {
    for (const row of db.prepare(sql).all() as { k?: string; id?: string }[]) {
      const value = row.k ?? row.id;
      if (value) found.add(value);
    }
  }
  return found;
}

// Relative "<bucket>/<aa>/<bb>/<file>" paths for every file in the store, with
// forward slashes so they compare against stored keys on any platform.
function listStoreFiles(root: string): string[] {
  const keys: string[] = [];
  const walk = (dir: string) => {
    let entries: fs.Dirent[];
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile()) keys.push(path.relative(root, full).split(path.sep).join("/"));
    }
  };
  walk(root);
  return keys;
}

export interface ThumbnailStoreAudit {
  files: number;
  orphans: number;
}

// Count files nothing points at. Read-only — nothing is removed here.
export function auditThumbnailStore(): ThumbnailStoreAudit {
  let root: string;
  try { root = getConfiguredThumbnailPath(); } catch { return { files: 0, orphans: 0 }; }

  const files = listStoreFiles(root);
  const referenced = collect(REFERENCED_KEY_QUERIES);
  const owners = collect(OWNER_ID_QUERIES);

  let orphans = 0;
  for (const key of files) {
    if (referenced.has(key)) continue;
    // thumbnailStorageKey builds every name as `${resourceId}-something`, and ids
    // are nanoid(16). A live owner means the file is a derived sibling, not junk.
    const owner = path.basename(key).slice(0, 16);
    if (owners.has(owner)) continue;
    orphans += 1;
  }
  return { files: files.length, orphans };
}

// Remove directories left empty by deletions, deepest first so a folder whose only
// contents were empty folders goes too. The store root itself is never removed, and
// a directory holding any file is left alone — so this can never take a thumbnail.
export function removeEmptyThumbnailDirs(): number {
  let root: string;
  try { root = getConfiguredThumbnailPath(); } catch { return 0; }

  let removed = 0;
  // Returns whether `dir` is empty once its own empty children have been removed.
  const prune = (dir: string): boolean => {
    let entries: fs.Dirent[];
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return false; }

    let keep = 0;
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      // Only directories are ever considered; a symlink is neither followed nor
      // removed, and any file at all makes the directory worth keeping.
      if (entry.isDirectory() && prune(full)) {
        try { fs.rmdirSync(full); removed += 1; } catch { keep += 1; }
      } else {
        keep += 1;
      }
    }
    return keep === 0;
  };

  prune(root); // the root's own emptiness is ignored — it is never removed
  return removed;
}
